/**
 * 照合用の文字正規化（rev 5章）: NFKC ＋ 前後空白の除去 ＋ 英字大文字小文字同一視のみ。
 * カナ同一視・送り仮名吸収はしない——恣意性が入るため、必要な表現は
 * alias に登録する運用に倒す（判断をアルゴリズムでなくデータに置く）。
 * name 重複判定と alias 照合はこの同じ規則を使うこと（規則を分けない）。
 *
 * 前後空白の除去は「表記ゆれの吸収」ではなく入力ノイズの除去。これが無いと
 * 末尾にスペースを足すだけで重複判定をすり抜けられる（語中の空白は別表記
 * として残す）。NFKC が全角スペースを半角化した後に trim する順序が必要。
 */
export function normalizeForMatch(s: string): string {
  return s.normalize('NFKC').trim().toLowerCase()
}
